/* Generate one atomic SQL Editor activation from the maintained migrations. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { database, migrations } = require('./local-database.cjs');

const files = [
  '20260907000000_catalog_security.sql',
  '20260912000000_catalog_editing.sql',
  '20260912010000_catalog_rest_crud.sql',
  '20260913000000_catalog_system_of_record.sql',
  '20260913010000_catalog_row_order.sql',
  '20260913020000_catalog_aliases.sql',
  '20260913030000_catalog_required_rules.sql',
  '20260913040000_catalog_access_options.sql',
];
const shapeQuery = `SELECT coalesce(jsonb_object_agg(table_name, columns), '{}'::jsonb) AS shape
  FROM (SELECT table_name, jsonb_agg(column_name ORDER BY column_name) AS columns
    FROM information_schema.columns WHERE table_schema='catalog' GROUP BY table_name) s`;
const literal = value => "'" + String(value).replaceAll("'", "''") + "'";

async function generate() {
  const db = await database({ bundle: true });
  let baseline;
  try { baseline = (await db.query(shapeQuery)).rows[0].shape; }
  finally { await db.close(); }
  const body = files.map(file => {
    const sql = fs.readFileSync(path.join(migrations, file), 'utf8').replace(/\r\n/g, '\n');
    if ((sql.match(/^BEGIN;$/gm) || []).length !== 1 || (sql.match(/^COMMIT;$/gm) || []).length !== 1) {
      throw new Error('Review transaction boundaries before bundling ' + file);
    }
    const hash = crypto.createHash('sha256').update(sql).digest('hex');
    return `-- Source: ${file}\n-- SHA-256 (LF): ${hash}\n` + sql.replace(/^BEGIN;\n/m, '').replace(/^COMMIT;\n?/m, '');
  }).join('\n');
  return `-- Generated by supabase/prepare-editing-activation.cjs. Do not edit this copy.
-- Target: Data Catalog / zicluerzbevodlmtbxow. Run the COMPLETE file as postgres.
-- Requires the original imported catalog, before editing migrations. Refuses reruns/partial activation.
-- Public signup must remain disabled. No original schema/import or catalog content is replayed.
-- Includes the security prerequisite: removes implicit grants for future postgres-owned objects.
-- One transaction: an error rolls back every activation change. Fix the cause before retrying.
BEGIN;
SET LOCAL search_path = pg_catalog;
SET LOCAL lock_timeout = '10s';
SELECT pg_advisory_xact_lock(hashtext('catalog-editing-activation'));
DO $preflight$
DECLARE actual jsonb;
BEGIN
  IF current_user <> 'postgres' THEN
    RAISE EXCEPTION 'Run the complete activation as postgres' USING ERRCODE='42501';
  END IF;
  SELECT shape INTO actual FROM (${shapeQuery}) baseline;
  IF actual IS DISTINCT FROM ${literal(JSON.stringify(baseline))}::jsonb
    OR to_regprocedure('catalog.read_snapshot()') IS NULL
    OR to_regprocedure('catalog.edit_capabilities()') IS NOT NULL
    OR to_regprocedure('catalog.save_entry(uuid,text,uuid,bigint,jsonb,jsonb)') IS NOT NULL
    OR to_regprocedure('catalog.api_write(text,text,uuid,bigint,jsonb,uuid)') IS NOT NULL
    OR to_regclass('catalog_private.edit_receipt') IS NOT NULL THEN
    RAISE EXCEPTION 'Catalog baseline differs or editing is already/partly activated. No changes applied. Review deployed migrations first.' USING ERRCODE='55000';
  END IF;
END;
$preflight$;

${body}

-- Validate availability and grants before committing. No test account or catalog row is created.
DO $verify$
BEGIN
  IF (SELECT count(*) FROM information_schema.columns WHERE table_schema='catalog') <> 477
    OR (SELECT count(*) FROM information_schema.tables WHERE table_schema='catalog' AND table_type='BASE TABLE') <> 19
    OR NOT has_function_privilege('authenticated','catalog.edit_capabilities()','EXECUTE')
    OR NOT has_function_privilege('authenticated','catalog.save_entry(uuid,text,uuid,bigint,jsonb,jsonb)','EXECUTE')
    OR NOT has_function_privilege('authenticated','catalog.api_write(text,text,uuid,bigint,jsonb,uuid)','EXECUTE')
    OR has_function_privilege('anon','catalog.edit_capabilities()','EXECUTE')
    OR (catalog.edit_capabilities()->>'access_options') IS DISTINCT FROM 'true'
    OR EXISTS (SELECT FROM information_schema.tables WHERE table_schema='catalog' AND table_type='BASE TABLE'
      AND (has_table_privilege('anon',format('catalog.%I',table_name),'INSERT,UPDATE,DELETE')
        OR has_table_privilege('authenticated',format('catalog.%I',table_name),'INSERT,UPDATE,DELETE'))) THEN
    RAISE EXCEPTION 'Activation verification failed; all changes rolled back' USING ERRCODE='55000';
  END IF;
END;
$verify$;
NOTIFY pgrst, 'reload schema';
COMMIT;
SELECT 'Editing database ready. Reload the app and sign in.' AS result,
  (SELECT count(*) FROM information_schema.columns WHERE table_schema='catalog') AS catalog_columns;
`;
}

async function main() {
  const sql = await generate(), output = path.join(__dirname,'.temp','activate-editing.sql');
  fs.mkdirSync(path.dirname(output),{recursive:true});
  fs.writeFileSync(output,sql,'utf8');
  console.log(`Prepared ${files.length} migrations in one transaction: ${output}`);
  console.log('No hosted connection or database change was made.');
}
if (require.main === module) main().catch(error=>{console.error(error);process.exitCode=1;});
module.exports = { generate, files, shapeQuery };
